"""Shared sepia palette of the old-cartoon look (art contract v3).

Read-only for the art generators: import the ramps, do not edit this file.
Each ramp goes from deep shadow to highlight. Colour is rare and muted; aged
paper and warm browns carry the picture.
"""


def rgba(code):
    code = code.lstrip("#")
    return (int(code[0:2], 16), int(code[2:4], 16), int(code[4:6], 16), 255)


def ramp(*codes):
    return [rgba(code) for code in codes]


